#!/usr/bin/env python3
"""Build the portrait registry from the reviewed academy sprite manifest.

Run after all img/bosses/<id>.webp assets exist. A single painted portrait
retains the existing container idle, hit, lunge and victory effects.
"""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
concepts = json.loads((ROOT/'docs/art/boss-sprite-concepts.json').read_text())
missing = [key for key in concepts if not (ROOT/f'img/bosses/{key}.webp').is_file()]
if missing:
    raise SystemExit('Missing sprite assets: '+', '.join(missing))
body = '''/* Academy boss portraits — generated by tools/build_boss_sprites.py.
   Stable boss IDs preserve existing progress. Container CSS handles motion. */
(function () {
  const ids = IDS;
  const sprites = {};
  ids.forEach(id => {
    sprites[id] = `<img class="boss-art" src="img/bosses/${id}.webp" width="384" height="384" alt="" decoding="async" draggable="false">`;
  });
  window.BOSS_SPRITES = Object.assign(window.BOSS_SPRITES || {}, sprites);
})();
'''.replace('IDS', json.dumps(list(concepts), indent=2))
(ROOT/'content/boss-sprites.js').write_text(body)
print(f'{len(concepts)} unique boss portraits registered')
